public class ForLoop
{
    static void main()
    {
       //task 1
        for(int x=0; x <= 30; x++)
        {
            System.out.print(x + " ");
        }

        System.out.println();
        System.out.println();

        //task 2
        for(int x=30; x >= 0; x--)
        {
            System.out.print(x + " ");
        }

        System.out.println();
        System.out.println();

        //task 3
        for(int x=0; x <= 18; x += 3)
        {
            System.out.print(x + " ");
        }

        System.out.println();
        System.out.println();

        //task 4
        for(int x=10; x>=0; x-=2)
        {
            System.out.print(x + " ");
        }

        System.out.println();
        System.out.println();



    }

}
